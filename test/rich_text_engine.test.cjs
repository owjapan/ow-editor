const { test, before, afterEach } = require('node:test')
const assert = require('node:assert/strict')
const { JSDOM } = require('jsdom')
let Engine, History, engine
before(async () => {
  const dom = new JSDOM('', { url: 'https://stg.example.test', pretendToBeVisual: true })
  global.window = dom.window; global.document = dom.window.document
  ;({ EditorEngine: Engine, History } = await import('../src/engine.mjs'))
})
afterEach(() => { engine?.destroy(); engine = null; document.body.innerHTML = '' })
function create(html) {
  const root = document.createElement('div'); document.body.append(root)
  engine = new Engine(root, { html }); return engine
}
test('independent engine preserves original HTML until editing and undo returns to original', () => {
  const original = '<p class="old">本文\nです</p>'
  const e = create(original)
  assert.equal(e.getHTML(), original); assert.equal(e.dirty, false)
  e.select(0, 2); e.command('bold')
  assert.match(e.getHTML(), /<strong>本文<\/strong>/)
  assert.equal(e.dirty, true)
  e.undo(); assert.equal(e.getHTML(), original); assert.equal(e.dirty, false)
  e.redo(); assert.equal(e.dirty, true)
})
test('inline marks toggle over partial selections and across paragraphs without corrupting blocks', () => {
  const e = create('<p><strong>abcdef</strong></p><p>ghij</p>')
  e.select(2, 4); e.command('bold')
  assert.match(e.getHTML(), /<strong>ab<\/strong>cd<strong>ef<\/strong>/)
  e.select(0, 10); e.command('italic')
  assert.equal(e.root.querySelectorAll('p').length, 2)
  assert.equal(e.root.textContent, 'abcdefghij')
  assert.equal(e.root.querySelector('p p'), null)
})
test('links, typography and block indentation survive serialization and another editor instance', () => {
  const e = create('<p>本文のテスト</p>')
  e.select(0, 2); e.command('link', { href: 'mailto:test@example.test', newTab: false })
  e.command('fontSize', '24px'); e.command('color', '#ff0000')
  e.command('indent', 1); e.command('align', 'center')
  const html = e.getHTML()
  assert.match(html, /mailto:test@example.test/); assert.match(html, /24px/)
  assert.match(html, /margin-left: 40px/); assert.match(html, /text-align: center/)
  assert.throws(() => e.command('link', { href: 'javascript:alert(1)' }))
  e.destroy(); engine = null
  assert.equal(create(html).root.textContent, '本文のテスト')
})
test('caption and image size edits preserve the existing upload URL and support undo', () => {
  const e = create('<p>画像</p>')
  e.select(3, 3)
  e.insertImage({ src: '/uploads/ckeditor/attachments/1/a.png', alt: '弁当', width: 320 })
  const image = e.root.querySelector('img'); e.selectNode(image)
  e.updateImage({ width: 480, alt: '新しい説明', caption: '画像下の説明', align: 'right' })
  assert.equal(e.root.querySelector('img').getAttribute('width'), '480')
  assert.equal(e.root.querySelector('figcaption').textContent, '画像下の説明')
  assert.match(e.getHTML(), /image-style-align-right/)
  assert.match(e.getHTML(), /\/uploads\/ckeditor\/attachments\/1\/a.png/)
  e.undo(); assert.equal(e.root.querySelector('figcaption'), null)
})
test('table grid supports merge/split and insertion/deletion through spanning cells without losing text', () => {
  const e = create('<table><tbody><tr><td><p>A</p></td><td><p>B</p></td></tr><tr><td><p>C</p></td><td><p>D</p></td></tr></tbody></table>')
  e.selectCell(0, 0); e.selectCell(1, 1, true); e.table('merge')
  assert.equal(e.root.querySelectorAll('td').length, 1)
  assert.equal(e.root.querySelector('td').colSpan, 2)
  assert.equal(e.root.querySelector('td').rowSpan, 2)
  assert.equal(e.root.textContent, 'ABCD')
  e.selectCell(0, 0); e.table('addRowAfter')
  assert.equal(e.root.querySelectorAll('tr').length, 3)
  e.selectCell(0, 0); e.table('split')
  assert.equal(e.root.querySelectorAll('td').length, 6)
  assert.equal(e.root.textContent, 'ABCD')
  e.selectCell(2, 1); e.table('deleteRow')
  assert.equal(e.root.querySelectorAll('tr').length, 2)
})
test('table properties apply to selected cells, retain formatting, and preserve head/body semantics', () => {
  const e = create('<table><thead><tr><th><p>見出し</p></th></tr></thead><tbody><tr><td><p>本文</p></td></tr></tbody></table>')
  e.selectCell(1, 0); e.table('style', { backgroundColor: '#fff59d', border: '2px solid #999', width: '180px', textAlign: 'right' })
  assert.equal(e.root.querySelectorAll('thead th').length, 1)
  assert.equal(e.root.querySelectorAll('tbody td').length, 1)
  assert.equal(e.root.querySelector('td').style.width, '180px')
  assert.equal(e.root.querySelector('td').style.textAlign, 'right')
})
test('HTML source is sanitized, malformed input cannot execute and IME creates one undo step', () => {
  const e = create('<p>前</p>')
  e.setHTML('<p>後<script>alert(1)</script><img src="/uploads/ckeditor/a.png" onerror="x()"></p>')
  assert.equal(e.root.querySelector('script,[onerror]'), null)
  e.undo(); assert.equal(e.root.textContent, '前')
  e.root.dispatchEvent(new window.CompositionEvent('compositionstart', { bubbles: true }))
  assert.equal(e.composing, true)
  e.root.innerHTML = '<p>前にほん</p>'
  e.root.dispatchEvent(new window.InputEvent('input', { inputType: 'insertCompositionText', isComposing: true, bubbles: true }))
  e.root.innerHTML = '<p>前日本語</p>'
  e.root.dispatchEvent(new window.CompositionEvent('compositionend', { data: '日本語', bubbles: true }))
  assert.equal(e.composing, false); assert.equal(e.root.textContent, '前日本語')
  e.undo(); assert.equal(e.root.textContent, '前')
})
test('independent history bounds memory, groups typing and invalidates redo after a new edit', () => {
  const h = new History({ html: '0', selection: { from: 0, to: 0 } }, { maxSteps: 3 })
  h.record({ html: '1' }, 'typing', 10); h.record({ html: '12' }, 'typing', 20)
  assert.equal(h.undo().html, '0'); assert.equal(h.redo().html, '12')
  h.record({ html: 'new' }, 'command', 40); h.record({ html: 'next' }, 'command', 50)
  assert.equal(h.canUndo, true)
  h.undo(); h.record({ html: 'branch' }, 'command', 60)
  assert.equal(h.canRedo, false)
  assert.ok(h.entries.length <= 3)
})
test('list indentation creates real nested lists and outdent restores the item order', () => {
  const e = create('<ul><li><p>一つ目</p></li><li><p>二つ目</p></li></ul>')
  e.select(5, 6); e.command('indent', 1)
  assert.equal(e.root.querySelectorAll('ul > li > ul > li').length, 1)
  e.command('indent', -1)
  assert.equal(e.root.querySelectorAll('ul ul').length, 0)
  assert.equal(e.root.textContent, '一つ目二つ目')
})
test('empty replacements delete text and source markup never retains editor-only selection classes', () => {
  const e = create('<p>abcabc</p>')
  assert.equal(e.replaceAll('b', ''), 2)
  assert.equal(e.root.textContent, 'acac')
  e.undo(); assert.equal(e.root.textContent, 'abcabc')
  e.setHTML('<table><tr><td class="rte-cell-selected"><p>A</p></td></tr></table>')
  assert.doesNotMatch(e.getHTML(), /rte-cell-selected/)
})
test('changing list type does not nest another list and structural edits preserve the typing position', () => {
  const e = create('<ul><li><p>一つ目</p></li><li><p>二つ目</p></li></ul>')
  e.select(6, 6); e.command('orderedList')
  assert.equal(e.root.querySelectorAll('ol').length, 1)
  assert.equal(e.root.querySelector('ul'), null)
  e.command('indent', 1); e.insertText('追記')
  assert.equal(e.root.textContent, '一つ目二追記つ目')
})
test('a rejected edit rolls back the document, selection and history atomically', () => {
  const e = create('<p>元の本文</p>')
  e.select(2, 2); const before = e.getHTML(), undo = e.canUndo
  assert.throws(() => e.insertHTML('<div>'.repeat(105) + '深い本文' + '</div>'.repeat(105)), /複雑/)
  assert.equal(e.getHTML(), before); assert.equal(e.root.textContent, '元の本文')
  assert.equal(e.canUndo, undo)
  assert.equal(e.selection.from, 2)
  e.insertText('追記'); assert.equal(e.root.textContent, '元の追記本文')
})
test('bulk replacement handles many matches and styled spans as one undoable edit', () => {
  const e = create('<p>' + 'A'.repeat(2000) + '</p>')
  assert.equal(e.replaceAll('A', 'BB'), 2000)
  assert.equal(e.root.textContent.length, 4000)
  e.undo(); assert.equal(e.root.textContent, 'A'.repeat(2000))
  e.setHTML('<p><strong>ab</strong><em>cd</em>ef</p>')
  assert.equal(e.replaceAll('bc', '置換'), 1)
  assert.equal(e.root.textContent, 'a置換def')
  assert.equal(e.root.querySelector('strong').textContent, 'a置換')
})
test('adding a caption to a legacy inline image splits its paragraph without losing surrounding text', () => {
  const e = create('<p>前の文章<img src="/uploads/ckeditor/pictures/1/a.png">後の文章</p>')
  e.selectNode(e.root.querySelector('img')); e.updateImage({ caption: '説明文', width: 240 })
  assert.equal(e.root.querySelector('p figure'), null)
  assert.equal(e.root.querySelector('figure figcaption').textContent, '説明文')
  assert.equal(e.root.textContent, '前の文章説明文後の文章')
  e.undo(); assert.equal(e.root.textContent, '前の文章後の文章')
})
test('an existing link can be selected as a whole across differently styled text for editing and removal', () => {
  const e = create('<p><a href="https://example.test"><strong>前半</strong>後半</a>本文</p>')
  e.select(1, 1)
  const range = e.getLinkRange()
  assert.equal(range.from, 0); assert.equal(range.to, 4)
  e.select(range.from, range.to); e.command('link', null)
  assert.equal(e.root.querySelector('a'), null)
  assert.equal(e.root.querySelector('strong').textContent, '前半')
})
